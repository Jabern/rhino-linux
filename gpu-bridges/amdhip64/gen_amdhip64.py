#!/usr/bin/env python3
"""Generate amdhip64_6.c and amdhip64_6.spec: a Wine builtin amdhip64_6.dll whose exports
pass Cycles' HIP calls on to ROCm's libamdhip64.so on Linux.

Prototypes come from Cycles 4.0's hipew.h (third_party/hipew.h), the Cycles of Rhino 8;
the exported functions are the ones Rhino's ccycles.dll looks up (hip-functions.txt). Run from this folder:
    python3 gen_amdhip64.py
"""
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
HEADER = HERE.parent / "third_party" / "hipew.h"
FUNCTIONS = [l.strip() for l in (HERE / "hip-functions.txt").read_text().splitlines()
             if l.strip() and not l.startswith("#")]

# Calls that can't work through Wine: OpenGL interop needs the Linux GL context of the
# Windows one, and a stream callback would run Windows code on a ROCm thread. Cycles
# falls back when they fail.
UNSUPPORTED = {
    "hipGLGetDevices", "hipGraphicsGLRegisterBuffer", "hipGraphicsMapResources",
    "hipGraphicsUnmapResources", "hipGraphicsUnregisterResource",
    "hipGraphicsResourceGetMappedPointer", "hipStreamAddCallback",
}
# Linux symbols tried in order for an export (ROCm 6 keeps the pre-6.0 layout of
# hipDeviceProp_t, which Rhino's Cycles was built with, as ...R0000).
SYMBOLS = {
    "hipGetDeviceProperties": ["hipGetDevicePropertiesR0000", "hipGetDeviceProperties"],
}

text = HEADER.read_text()
protos = {}
for m in re.finditer(r"typedef\s+(\w+)\s+HIPAPI\s+t(hip\w+)\s*\(([^;]*?)\)\s*;", text, re.S):
    ret, name, args = m.group(1), m.group(2), " ".join(m.group(3).split())
    protos[name] = (ret, args)
# Older HIP calls Rhino's Cycles looks up that hipew.h doesn't declare
protos.setdefault("hipConfigureCall", ("hipError_t", "dim3 gridDim, dim3 blockDim, size_t sharedMem, hipStream_t stream"))
protos.setdefault("hipRuntimeGetVersion", ("hipError_t", "int* runtimeVersion"))


def arg_names(args):
    if args in ("", "void"):
        return []
    names = []
    for a in args.split(","):
        a = a.strip()
        m = re.search(r"(\w+)\s*(\[\s*\])?$", a)
        names.append(m.group(1))
    return names


c = ['/* Generated by gen_amdhip64.py from Cycles\' hipew.h: do not edit. */',
     '',
     '#include "amdhip64_private.h"',
     '']
spec = ["# Generated by gen_amdhip64.py: do not edit."]
loads = []
missing = []
for name in FUNCTIONS:
    if name not in protos:
        missing.append(name)
        continue
    ret, args = protos[name]
    names = arg_names(args)
    if name not in UNSUPPORTED:
        c.append(f"static {ret} (*p_{name})({args or 'void'});")
    c.append(f"{ret} WINAPI wine_{name}({args or 'void'})")
    c.append("{")
    c.append(f"    WINE_TRACE(\"\\n\");")
    if name in UNSUPPORTED:
        c.append(f"    WINE_FIXME(\"not supported through Wine\\n\");")
        c.append("    return hipErrorNotSupported;")
    else:
        missing_ret = "hipErrorNoDevice" if name in ("hipInit", "hipGetDeviceCount") else "hipErrorNotSupported"
        c.append(f"    if (!p_{name}) return {missing_ret};")
        call = f"p_{name}({', '.join(names)})"
        if name == "hipModuleLoad":
            c.append("    {")
            c.append("        char *unix_name = unix_path(fname);")
            c.append(f"        hipError_t ret = p_{name}(module, unix_name ? unix_name : fname);")
            c.append("        free_unix_path(unix_name);")
            c.append("        return ret;")
            c.append("    }")
        else:
            c.append(f"    return {call};")
    c.append("}")
    c.append("")
    spec.append(f"@ cdecl -norelay {name}() wine_{name}")
    if name not in UNSUPPORTED:
        syms = SYMBOLS.get(name, [name])
        loads.append(f"    LOAD({name}, {', '.join(f'{s!r}'.replace(chr(39), chr(34)) for s in syms)});")

c.append("void load_functions(void *lib)")
c.append("{")
c.extend(loads)
c.append("}")
(HERE / "amdhip64_6_thunks.c").write_text("\n".join(c) + "\n")
(HERE / "amdhip64_6.spec").write_text("\n".join(spec) + "\n")
if missing:
    raise SystemExit(f"no prototype in hipew.h for: {', '.join(missing)}")
print(f"{len(FUNCTIONS)} functions")
