#!/usr/bin/env python3
"""Generate ze_loader_thunks.c and ze_loader.spec: a Wine builtin ze_loader.dll whose exports
pass Level Zero calls on to the Linux loader, libze_loader.so.1, and through it to Intel's
compute runtime.

Prototypes come from Level Zero's ze_api.h and zes_api.h (third_party/); the exported
functions are the ones Rhino's pi_level_zero.dll imports (ze-functions.txt). Run from this
folder:
    python3 gen_ze_loader.py
"""
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
HEADERS = [HERE.parent / "third_party" / "ze_api.h", HERE.parent / "third_party" / "zes_api.h"]
FUNCTIONS = [l.strip() for l in (HERE / "ze-functions.txt").read_text().splitlines()
             if l.strip() and not l.startswith("#")]

# Loader tracing calls Windows callbacks from Linux code; pi_level_zero only uses it
# when its debugging is turned on, and goes on without it.
UNSUPPORTED = {"zelTracerCreate", "zelTracerSetEnabled", "zelTracerSetEpilogues", "zelTracerSetPrologues"}

protos = {}
for header in HEADERS:
    text = re.sub(r"///<[^\n]*", "", header.read_text())
    for m in re.finditer(r"ZE_APIEXPORT\s+(\w+)\s+ZE_APICALL\s+(z\w+)\s*\(([^;]*?)\)\s*;", text, re.S):
        ret, name, args = m.group(1), m.group(2), " ".join(m.group(3).split())
        protos[name] = (ret, args)


def arg_names(args):
    if args in ("", "void"):
        return []
    return [re.search(r"(\w+)\s*(\[\s*\w*\s*\])?$", a.strip()).group(1) for a in args.split(",")]


c = ["/* Generated by gen_ze_loader.py from Level Zero's ze_api.h and zes_api.h: do not edit. */",
     "",
     '#include "ze_loader_private.h"',
     ""]
spec = ["# Generated by gen_ze_loader.py: do not edit."]
loads = []
missing = []
for name in FUNCTIONS:
    spec.append(f"@ cdecl -norelay {name}() wine_{name}")
    if name in UNSUPPORTED:
        c.append(f"ze_result_t WINAPI wine_{name}(void)")
        c.append("{")
        c.append('    WINE_FIXME("loader tracing is not supported through Wine\\n");')
        c.append("    return ZE_RESULT_ERROR_UNSUPPORTED_FEATURE;")
        c.append("}")
        c.append("")
        continue
    if name not in protos:
        missing.append(name)
        continue
    ret, args = protos[name]
    names = arg_names(args)
    if name != "zeDriverGetExtensionFunctionAddress":
        c.append(f"static {ret} (*p_{name})({args or 'void'});")
    c.append(f"{ret} WINAPI wine_{name}({args or 'void'})")
    c.append("{")
    c.append('    WINE_TRACE("\\n");')
    if name == "zeDriverGetExtensionFunctionAddress":
        # The address would be a Linux function, which Windows code can't call: report
        # the extension as missing, as for a driver without it.
        c.append("    WINE_FIXME(\"extension %s not available through Wine\\n\", wine_dbgstr_a(name));")
        c.append("    if (ppFunctionAddress) *ppFunctionAddress = NULL;")
        c.append("    return ZE_RESULT_ERROR_INVALID_ARGUMENT;")
    else:
        missing_ret = "ZE_RESULT_ERROR_UNINITIALIZED" if name in ("zeInit", "zeDriverGet") else "ZE_RESULT_ERROR_UNSUPPORTED_FEATURE"
        c.append(f"    if (!p_{name}) return {missing_ret};")
        c.append(f"    return p_{name}({', '.join(names)});")
    c.append("}")
    c.append("")
    if name != "zeDriverGetExtensionFunctionAddress":
        loads.append(f'    LOAD({name});')

c.append("void load_functions(void *lib)")
c.append("{")
c.extend(loads)
c.append("}")
if missing:
    raise SystemExit(f"no prototype for: {', '.join(missing)}")
(HERE / "ze_loader_thunks.c").write_text("\n".join(c) + "\n")
(HERE / "ze_loader.spec").write_text("\n".join(spec) + "\n")
print(f"{len(FUNCTIONS)} functions")
